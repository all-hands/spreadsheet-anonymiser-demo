// @vitest-environment node
import { readFileSync } from 'node:fs';
import { describe, expect, it, vi } from 'vitest';

const FIXTURES = new URL('../../../crates/anonymiser-cli/tests/fixtures/kyber-0.0.2/', import.meta.url);
const fixture = (name: string): Buffer => readFileSync(new URL(name, FIXTURES));

const anonSalt = (file: Buffer): Uint8Array => {
    expect(file.subarray(0, 9).toString('latin1')).toBe('ANONSALT\x01');
    return new Uint8Array(file.subarray(9, 9 + 32));
};

vi.mock('./wasm', async () => {
    const { readFileSync: read } = await import('node:fs');
    const dir = new URL('../wasm-pkg/', import.meta.url);
    // eslint-disable-next-line @typescript-eslint/ban-ts-comment
    // @ts-ignore — generated by scripts/build-wasm.sh (wasm-bindgen)
    const glue = await import('../wasm-pkg/anonymiser_wasm');
    glue.initSync({ module: read(new URL('anonymiser_wasm_bg.wasm', dir)) });
    const salt = read(
        new URL('../../../crates/anonymiser-cli/tests/fixtures/kyber-0.0.2/pp-salt.anonsalt', import.meta.url)
    );
    return {
        ...glue,
        ensureWasm: async () => {},
        generate_salt: () => new Uint8Array(salt.subarray(9, 41)),
    };
});

import { anonymizeData, decryptData } from './anonymize';
import { parseTextInMemory } from './parse-text';
import { endSession, startSession } from './session';

const PASSPHRASE = 'correct horse battery staple';
const NOTICE =
    'policy "kyber-aes" is deprecated and refused for new runs: its ML-KEM layer is keyed ' +
    'from the column key, so it adds no protection over AES-256-GCM; use "encrypt" instead ' +
    '(existing kyber:v1: cells still decrypt)';
const noop = () => {};

const parse = (name: string) =>
    parseTextInMemory(new File([fixture(name).toString('utf8')], name), 'csv', noop);

describe('kyber-aes after its deprecation (real wasm)', () => {
    it('decrypts the kyber:v1: cells of a 0.0.2 run with the old passphrase and salt', async () => {
        expect(anonSalt(fixture('pp-salt.anonsalt'))).toHaveLength(32);
        endSession();
        await startSession(PASSPHRASE);
        const old = await parse('pp-out.csv');
        expect(old.data.filter((r) => String(r[0]).startsWith('kyber:v1:'))).toHaveLength(2);

        const { data, decrypted } = await decryptData(old.data, old.headers, noop, { dataset: 'demo' });
        const original = await parse('in.csv');
        expect(decrypted).toBe(2);
        expect(data).toEqual(original.data);
        endSession();
    });

    it('refuses a new kyber-aes run with the core notice, keyed or not', async () => {
        const input = await parse('in.csv');
        const run = () =>
            anonymizeData(input.data, input.headers, input.metadata, { 0: { type: 'kyber-aes' } }, noop, {
                dataset: 'demo',
            });
        endSession();
        await expect(run()).rejects.toThrow(NOTICE);
        await startSession(PASSPHRASE);
        await expect(run()).rejects.toThrow(NOTICE);
        endSession();
    });
});
